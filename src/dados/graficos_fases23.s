#    blocos 19 a 29 (no mapa: J a T) e os cenários do laboratório e do circuito
#    mapas: mapa_aed e mapa_aoc
#
#  As imagens daqui entram na tabela_desenhos (fim do dados/graficos.s) e os mapas
#  na tabela_mapas; os blocos estão na tabela 'blocos'.
#
#  REGRA DOS MAPAS: o pulo cobre só uns 32 pixels na horizontal. Espinhos (S, T)
#  que precisam ser pulados devem ter 1 bloco de largura, e vãos entre
#  plataformas também 1 bloco. Com 2 blocos o pulo quase nunca dá certo.
